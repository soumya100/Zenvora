export type TranslationKey = keyof typeof translations['en'];

/**
 * Resolve settings language to supported locale code
 */
export function resolveLanguage(prefLanguage: string): SupportedLanguage {
  if (prefLanguage && prefLanguage !== 'auto') {
    const code = prefLanguage.toLowerCase().substring(0, 2) as SupportedLanguage;
    if (code in translations) {
      return code;
    }
  }

  // Automatic browser resolution
  if (typeof navigator !== 'undefined' && navigator.language) {
    const browserCode = navigator.language.toLowerCase().substring(0, 2) as SupportedLanguage;
    if (browserCode in translations) {
      return browserCode;
    }
  }

  return 'en';
}

/**
 * Hook providing translated strings and synchronization with document lang attribute
 */
export function useTranslation() {
  const { settings } = useSettings();
  const currentLang = resolveLanguage(settings.language);

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = currentLang;
    }
  }, [currentLang]);

  const t = (key: TranslationKey, params?: Record<string, string | number>): string => {
    const langDictionary = translations[currentLang] || translations.en;
    let text: string = langDictionary[key] || translations.en[key] || key;

    if (params) {
      Object.entries(params).forEach(([paramKey, paramVal]) => {
        text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal));
      });
    }

    return text;
  };

  return {
    t,
    currentLang,
    isAuto: settings.language === 'auto',
  };
}
